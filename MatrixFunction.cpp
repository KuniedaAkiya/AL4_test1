// ===== 行列生成関数 =====

// 行列の積（m1 * m2）
Matrix4x4 Multiply(const Matrix4x4& m1, const Matrix4x4& m2) {
	Matrix4x4 result = {};
	for (int i = 0; i < 4; ++i) {
		for (int j = 0; j < 4; ++j) {
			for (int k = 0; k < 4; ++k) {
				result.m[i][j] += m1.m[i][k] * m2.m[k][j];
			}
		}
	}
	return result;
}

// X軸回転行列
Matrix4x4 MakeRotateXMatrix(float radian) {
	Matrix4x4 result = {};
	result.m[0][0] = 1.0f;
	result.m[3][3] = 1.0f;
	result.m[1][1] = std::cos(radian);
	result.m[1][2] = std::sin(radian);
	result.m[2][1] = -std::sin(radian);
	result.m[2][2] = std::cos(radian);
	return result;
}

// Y軸回転行列
Matrix4x4 MakeRotateYMatrix(float radian) {
	Matrix4x4 result = {};
	result.m[1][1] = 1.0f;
	result.m[3][3] = 1.0f;
	result.m[0][0] = std::cos(radian);
	result.m[0][2] = -std::sin(radian);
	result.m[2][0] = std::sin(radian);
	result.m[2][2] = std::cos(radian);
	return result;
}

// Z軸回転行列
Matrix4x4 MakeRotateZMatrix(float radian) {
	Matrix4x4 result = {};
	result.m[2][2] = 1.0f;
	result.m[3][3] = 1.0f;
	result.m[0][0] = std::cos(radian);
	result.m[0][1] = std::sin(radian);
	result.m[1][0] = -std::sin(radian);
	result.m[1][1] = std::cos(radian);
	return result;
}

// アフィン変換行列の作成関数
Matrix4x4 MakeAffineMatrix(const Vector3& scale, const Vector3& rotate, const Vector3& translate) {
	// 拡大縮小行列 (Scale)
	Matrix4x4 matScale = {};
	matScale.m[0][0] = scale.x;
	matScale.m[1][1] = scale.y;
	matScale.m[2][2] = scale.z;
	matScale.m[3][3] = 1.0f;

	// 回転行列 (Rotate) X -> Y -> Z の順で合成する場合
	Matrix4x4 matRotX = MakeRotateXMatrix(rotate.x);
	Matrix4x4 matRotY = MakeRotateYMatrix(rotate.y);
	Matrix4x4 matRotZ = MakeRotateZMatrix(rotate.z);

	// 回転の合成順序
	Matrix4x4 matRotate = Multiply(matRotX, Multiply(matRotY, matRotZ));

	// 平行移動行列 (Translate)
	Matrix4x4 matTranslate = {};
	matTranslate.m[0][0] = 1.0f;
	matTranslate.m[1][1] = 1.0f;
	matTranslate.m[2][2] = 1.0f;
	matTranslate.m[3][3] = 1.0f;
	matTranslate.m[3][0] = translate.x;
	matTranslate.m[3][1] = translate.y;
	matTranslate.m[3][2] = translate.z;

	// 合成 (Scale * Rotate * Translate)
	Matrix4x4 result = Multiply(matScale, Multiply(matRotate, matTranslate));

	return result;
}

