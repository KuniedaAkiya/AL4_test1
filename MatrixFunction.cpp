// 透視投影行列（Projection Matrix）
Matrix4x4 MakePerspectiveFovMatrix(float fovY, float aspectRatio, float nearClip, float farClip) {
	Matrix4x4 result = {};
	float h = 1.0f / std::tan(fovY / 2.0f);
	float w = h / aspectRatio;
	result.m[0][0] = w;
	result.m[1][1] = h;
	result.m[2][2] = farClip / (farClip - nearClip);
	result.m[2][3] = 1.0f;
	result.m[3][2] = (-nearClip * farClip) / (farClip - nearClip);
	return result;
}

// ===== 補間・当たり判定関数 =====

// 線形補間（イージング付き）
float Lerp(float start, float end, float t, float tmax) {
	float newt = t / tmax;
	newt = 1.0f - newt;
	float easedt = newt * newt;
	return (1.0f - easedt) * start + easedt * end;
}

// 線形補間（Vector3版）
Vector3 Lerp(const Vector3& start, const Vector3& end, float interpolationRate) {
	Vector3 result = {};
	result.x = start.x + (end.x - start.x) * interpolationRate;
	result.y = start.y + (end.y - start.y) * interpolationRate;
	result.z = start.z + (end.z - start.z) * interpolationRate;
	return result;
}

// AABB同士の交差判定
bool IsCollisionAABB(const AABB& aabb1, const AABB& aabb2) {
	return (aabb1.min.x <= aabb2.max.x && aabb1.max.x >= aabb2.min.x) && (aabb1.min.y <= aabb2.max.y && aabb1.max.y >= aabb2.min.y) && (aabb1.min.z <= aabb2.max.z && aabb1.max.z >= aabb2.min.z);
}

// ---- 【追加】イージング関数 ----

// イーズイン (EaseInQuad)
float EaseIn(float start, float end, float t) {
	// t は 0.0f から 1.0f の範囲に制限する
	float clampedT = (t < 0.0f) ? 0.0f : ((t > 1.0f) ? 1.0f : t);

	// tの2乗で補間率を計算
	float rate = clampedT * clampedT;
	return start + (end - start) * rate;
}

// イーズアウト (EaseOutQuad)
float EaseOut(float start, float end, float t) {
	// t は 0.0f から 1.0f の範囲に制限する
	float clampedT = (t < 0.0f) ? 0.0f : ((t > 1.0f) ? 1.0f : t);

	// 1 - (1 - t)^2 で補間率を計算
	float rate = 1.0f - (1.0f - clampedT) * (1.0f - clampedT);
	return start + (end - start) * rate;
}